void showArrow(const unsigned char* arrowBitmap) {
  display.clearDisplay();
  display.drawBitmap(0, 0, arrowBitmap, 128, 64, WHITE);
  display.display();
}

void setup() {
  Serial.begin(115200);

  // initialize the OLED object
  if (!display.begin(SSD1306_SWITCHCAPVCC, SCREEN_ADDRESS)) {
    Serial.println(F("SSD1306 allocation failed"));
    for (;;)
      ;
  }
}

int primary_dir = 0;
  int secondary_dir = 0;

void loop() {
	Serial.println("X: " + String(analogRead(JOY_X)) + ", Y: " + String(analogRead(JOY_Y)));

	int x = analogRead(JOY_X);
	int y = analogRead(JOY_Y);

	int xb = analogRead(JOYB_X);
	int yb = analogRead(JOYB_Y);

	// find primary arrow
	if (x < 1000) {
		if (y < 1000) {
			primary_dir = 4;
		} else if (y > 2500) {
			primary_dir = 6;
		} else {
			primary_dir = 2;
		}
	} else if (x > 2500) {
		if (y < 1000) {
			primary_dir = 5;
		} else if (y > 2500) {
			primary_dir = 7;
		} else {
			primary_dir = 3;
		}
	} else {
		if (y < 1000) {
			primary_dir = 0;
		} else if (y > 2500) {
			primary_dir = 1;
		}
	}

	// find secondary arrow
	if (xb < 1000) {
		if (yb < 1000) {
			secondary_dir = 4;
		} else if (yb > 2500) {
			secondary_dir = 6;
		} else {
			secondary_dir = 2;
		}
	} else if (xb > 2500) {
		if (yb < 1000) {
			secondary_dir = 5;
		} else if (yb > 2500) {
			secondary_dir = 7;
		} else {
			secondary_dir = 3;
		}
	} else {
		if (yb < 1000) {
			secondary_dir = 0;
		} else if (yb > 2500) {
			secondary_dir = 1;
		}
	}

	showArrow(ARROW_BITMAP(primary_dir, secondary_dir));
}
